 def gps_base(self):
  # ECEF to ENU, subtract current antenna lever arm using robot TF.
  def ecef(lat,lon,h):
   a=6378137.;e2=6.69437999014e-3;la=math.radians(lat);lo=math.radians(lon);n=a/math.sqrt(1-e2*math.sin(la)**2)
   return ((n+h)*math.cos(la)*math.cos(lo),(n+h)*math.cos(la)*math.sin(lo),(n*(1-e2)+h)*math.sin(la))
  ref=ecef(13.0827,80.2707,0);p=ecef(self.gps.latitude,self.gps.longitude,self.gps.altitude);dx,dy,dz=[p[i]-ref[i] for i in range(3)];la=math.radians(13.0827);lo=math.radians(80.2707)
  east=-math.sin(lo)*dx+math.cos(lo)*dy;north=-math.sin(la)*math.cos(lo)*dx-math.sin(la)*math.sin(lo)*dy+math.cos(la)*dz
  t=self.tf.lookup_transform('base_footprint','gnss_link',rclpy.time.Time()).transform.translation
  yaw=self.yaw();return [east-(math.cos(yaw)*t.x-math.sin(yaw)*t.y),north-(math.sin(yaw)*t.x+math.cos(yaw)*t.y)]
 def yaw(self):
  q=self.imu.orientation;return math.atan2(2*(q.w*q.z+q.x*q.y),1-2*(q.y*q.y+q.z*q.z))
 def precision(self,target):
  end=time.monotonic()+45;dwell=None;commands=0;minclear=math.inf;start=time.monotonic()
  try:
   while time.monotonic()<end:
    self.spin(.10);now=time.monotonic()
    if self.gps.status.status<0:raise RuntimeError('GPS fix is invalid')
    if max(now-self.gpswall,now-self.odomwall,now-self.scanwall,now-self.imuwall)>1.:raise RuntimeError('Stale GPS, odometry or scan')
    sim=self.get_clock().now().nanoseconds/1e9
    for m in [self.gps,self.odom,self.scan,self.imu]:
     stamp=m.header.stamp.sec+m.header.stamp.nanosec/1e9
     if not -.05<=sim-stamp<=.6:raise RuntimeError('Sensor simulation timestamps are stale')
    gps=self.gps_base();valid=[r for r in self.scan.ranges if math.isfinite(r) and self.scan.range_min<=r<=self.scan.range_max]
    if not valid:raise RuntimeError('Scan has no usable ranges')
    clearance=min(valid);minclear=min(minclear,clearance);v,w,arrived=precision_command(target[0]-gps[0],target[1]-gps[1],self.yaw(),clearance)
    self.feedback.append({'sim_s':sim,'gps_base':gps,'heading_rad':self.yaw(),'target_world':target,'v_m_s':v,'w_rad_s':w,'min_scan_range_m':clearance});msg=Twist();msg.linear.x=v;msg.angular.z=w;self.recovery.publish(msg);commands+=1
    stopped=self.wheel is not None and now-self.wheelwall<1. and abs(self.wheel.twist.twist.linear.x)<.02 and abs(self.imu.angular_velocity.z)<.04
    if arrived and stopped:
     if dwell is None:dwell=sim
     if sim-dwell>=1.:return {'status':'gps_arrival_verified','commands':commands,'min_scan_range_m':minclear,'elapsed_wall_s':now-start,'gps_error_m':math.dist(gps,target),'stopped_dwell_sim_s':sim-dwell}
    else:dwell=None
   raise RuntimeError('GPS final approach timed out')
  finally:
   self.recovery.publish(Twist());self.spin(.7)
 def tolerance(self,value):
  c=self.create_client(SetParameters,"/controller_server/set_parameters"); req=SetParameters.Request();req.parameters=[Parameter(name="general_goal_checker.xy_goal_tolerance",value=ParameterValue(type=ParameterType.PARAMETER_DOUBLE,double_value=value))];f=c.call_async(req);end=time.monotonic()+5
  while not f.done() and time.monotonic()<end:self.spin(.1)
  if not f.done() or not all(r.successful for r in f.result().results):raise RuntimeError("Goal tolerance update failed")
  self.destroy_client(c)
 def goal(self,x,y,yaw=0):
  g=NavigateToPose.Goal();g.pose.header.frame_id='map';g.pose.header.stamp=self.get_clock().now().to_msg();g.pose.pose.position.x=float(x);g.pose.pose.position.y=float(y);g.pose.pose.orientation.z=math.sin(yaw/2);g.pose.pose.orientation.w=math.cos(yaw/2)
  f=self.action.send_goal_async(g);end=time.monotonic()+15
  while not f.done() and time.monotonic()<end:self.spin(.1)
  if not f.done():return {'status':'goal_send_timeout'}
  h=f.result()
  if not h.accepted:return {'status':'rejected'}
  r=h.get_result_async();end=time.monotonic()+110
  while not r.done() and time.monotonic()<end:self.spin(.1)
  if not r.done():h.cancel_goal_async();self.spin(2);return {'status':'timeout'}
  self.spin(1.2);p=self.truth.pose.pose.position;b=self.tf.lookup_transform('map','base_footprint',rclpy.time.Time()).transform.translation
  return {'status':r.result().status,'truth':[p.x,p.y],'map':[b.x,b.y],'gps_base':self.gps_base(),'gps_fresh':time.monotonic()-self.gpswall<2,'stopped':abs(self.odom.twist.twist.linear.x)<.03 and abs(self.odom.twist.twist.angular.z)<.05}
